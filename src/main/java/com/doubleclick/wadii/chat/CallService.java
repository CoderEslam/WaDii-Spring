package com.doubleclick.wadii.chat;

import com.doubleclick.wadii.common.error.BusinessException;
import com.doubleclick.wadii.common.error.ErrorCode;
import com.doubleclick.wadii.common.security.AuthUser;
import com.doubleclick.wadii.notification.PushGateway;
import lombok.RequiredArgsConstructor;
import org.springframework.messaging.simp.SimpMessagingTemplate;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Clock;
import java.time.Duration;
import java.time.Instant;
import java.util.EnumSet;
import java.util.Map;

/**
 * Voice/video calls between the two participants of an order conversation. The channel name is generated by the
 * server ({@code conv_<id>}) and RTC tokens are only issued to a participant, for themselves (uid = own user id).
 * Signaling events go to {@code /user/queue/calls} and, for the invite, as an FCM data push.
 */
@Service
@RequiredArgsConstructor
public class CallService {

    private final ConversationService conversationService;
    private final CallRepository callRepository;
    private final RtcTokenService rtcTokenService;
    private final SimpMessagingTemplate messaging;
    private final PushGateway pushGateway;
    private final Clock clock;

    public record CallView(Long id, Long conversationId, Long callerId, Long calleeId, CallType callType, CallStatus status,
                           String channelName, Instant startedAt, Instant answeredAt, Instant endedAt, Long durationSeconds) {
        static CallView of(Call c) {
            return new CallView(c.getId(), c.getConversationId(), c.getCallerId(), c.getCalleeId(), c.getCallType(), c.getStatus(),
                    c.getChannelName(), c.getStartedAt(), c.getAnsweredAt(), c.getEndedAt(), c.getDurationSeconds());
        }
    }

    public record CallSession(CallView call, RtcTokenService.RtcToken token) {
    }

    @Transactional
    public CallSession start(AuthUser me, Long conversationId, CallType type, RtcTokenService.Vendor vendor) {
        Conversation c = conversationService.requireParticipant(me, conversationId);
        Call call = new Call();
        call.setConversationId(c.getId());
        call.setCallerId(me.id());
        call.setCalleeId(c.otherParticipant(me.id()));
        call.setCallType(type == null ? CallType.AUDIO : type);
        call.setChannelName("conv_" + c.getId());
        call.setStartedAt(clock.instant());
        call = callRepository.save(call);
        CallView view = CallView.of(call);
        messaging.convertAndSendToUser(String.valueOf(call.getCalleeId()), "/queue/calls", Map.of("event", "CALL_INVITE", "call", view));
        pushGateway.sendData(call.getCalleeId(), Map.of("event", "CALL_INVITE", "callId", String.valueOf(call.getId()),
                "conversationId", String.valueOf(c.getId()), "callType", call.getCallType().name(), "fromUserId", String.valueOf(me.id())));
        return new CallSession(view, rtcTokenService.issue(vendor, call.getChannelName(), me.id()));
    }

    @Transactional
    public CallSession accept(AuthUser me, Long callId, RtcTokenService.Vendor vendor) {
        Call call = load(callId);
        if (!call.getCalleeId().equals(me.id())) throw BusinessException.forbidden("Only the callee can accept this call");
        if (call.getStatus() != CallStatus.RINGING) throw BusinessException.of(ErrorCode.CONFLICT, "The call is " + call.getStatus());
        call.setStatus(CallStatus.ONGOING);
        call.setAnsweredAt(clock.instant());
        signal(call, "CALL_ACCEPT", call.getCallerId());
        return new CallSession(CallView.of(call), rtcTokenService.issue(vendor, call.getChannelName(), me.id()));
    }

    @Transactional
    public CallView reject(AuthUser me, Long callId) {
        Call call = load(callId);
        if (!call.getCalleeId().equals(me.id())) throw BusinessException.forbidden("Only the callee can reject this call");
        if (call.getStatus() != CallStatus.RINGING) throw BusinessException.of(ErrorCode.CONFLICT, "The call is " + call.getStatus());
        call.setStatus(CallStatus.REJECTED);
        call.setEndedAt(clock.instant());
        signal(call, "CALL_REJECT", call.getCallerId());
        return CallView.of(call);
    }

    @Transactional
    public CallView end(AuthUser me, Long callId) {
        Call call = load(callId);
        if (!call.getCallerId().equals(me.id()) && !call.getCalleeId().equals(me.id())) throw BusinessException.forbidden();
        if (!EnumSet.of(CallStatus.RINGING, CallStatus.ONGOING).contains(call.getStatus())) return CallView.of(call);
        Instant now = clock.instant();
        call.setStatus(call.getStatus() == CallStatus.RINGING ? CallStatus.MISSED : CallStatus.ENDED);
        call.setEndedAt(now);
        call.setDurationSeconds(call.getAnsweredAt() == null ? 0L : Duration.between(call.getAnsweredAt(), now).getSeconds());
        signal(call, "CALL_END", call.getCallerId().equals(me.id()) ? call.getCalleeId() : call.getCallerId());
        return CallView.of(call);
    }

    /** A fresh token for an ongoing call, for the caller only (reconnects). */
    @Transactional(readOnly = true)
    public RtcTokenService.RtcToken token(AuthUser me, Long callId, RtcTokenService.Vendor vendor) {
        Call call = load(callId);
        if (!call.getCallerId().equals(me.id()) && !call.getCalleeId().equals(me.id())) throw BusinessException.forbidden();
        if (call.getStatus() != CallStatus.ONGOING && call.getStatus() != CallStatus.RINGING) {
            throw BusinessException.of(ErrorCode.CONFLICT, "The call is " + call.getStatus());
        }
        return rtcTokenService.issue(vendor, call.getChannelName(), me.id());
    }

    private void signal(Call call, String event, Long to) {
        messaging.convertAndSendToUser(String.valueOf(to), "/queue/calls", Map.of("event", event, "call", CallView.of(call)));
    }

    private Call load(Long id) {
        return callRepository.findById(id).orElseThrow(() -> BusinessException.notFound(ErrorCode.NOT_FOUND));
    }
}
